def test_is_valid_birth_date_with_valid_dates(faker_obj):
    """Tests the method 'SystemService.is_valid_birth_date()'.
    It should return True for valid birth dates generated by Faker.
    """
    for _ in range(10):
        birth_date = faker_obj.date_of_birth(
            maximum_age=SystemService.MAX_AGE
        ).strftime("%d/%m/%Y")

        assert SystemService.is_valid_birth_date(birth_date)


