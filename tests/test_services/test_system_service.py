def test_find_client_by_id(clients_objs):
    """Tests the method 'SystemService.find_client()'.
    It should return the Client instance when searching by ID, CPF or RG.
    """

    for client in clients_objs:
        id, cpf, rg = client.id, client.cpf, client.rg

        for info in (id, cpf, rg):
            found = SystemService.find_client(info)

            assert found.id == client.id


def test_find_client_returns_none_when_not_found():
    """Tests the method 'SystemService.find_client()'.
    It should return 'None' when no client matches ID, RG, or CPF.
    """

    assert not SystemService.find_client("00000000000")





